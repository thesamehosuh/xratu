import { strict as assert } from 'node:assert';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { SubagentTraceCollector, readSubagentTrace, boundSubagentEvents, TRACE_CHARS, TRACE_ENTRIES } = require('../out/subagentObservation.js');
const { trimDisplayEvent } = require('../out/local/eventBounds.js');
let now = 1000;
const snapshots = [];
const collector = new SubagentTraceCollector({ taskId: 'child', profile: 'explore', description: 'Find expiry', prompt: 'Read the implementation', model: 'child-model', effort: 'high', tools: ['read_file'], resumed: false, status: 'running', startedAt: now, updatedAt: now, entries: [], toolCalls: 0, inputTokens: 0, outputTokens: 0 }, trace => snapshots.push(trace), () => now);
const send = event => { now += 100; collector.receive(event); };
send({type:'thinking', value:'first'});
send({type:'thinking', value:'first second'});
send({type:'chunk', value:'Checking'});
send({type:'assistantMessage', text:'Checking the file', toolCalls:[]});
send({type:'toolCall', id:'read', tool:'read_file', args:{path:'a.ts'}});
const beforeApproval = JSON.stringify(snapshots.at(-1));
send({type:'needsApproval', approvalId:'approve', approvals:[{tool_name:'read_file'}]});
assert.equal(snapshots.at(-1).status, 'waiting');
assert.equal(JSON.stringify(snapshots.at(-2)), beforeApproval, 'published snapshots cannot be mutated by later events');
send({type:'toolOutput', id:'read', value:'live content'});
send({type:'toolResult', id:'read', tool:'read_file', output:'', isError:true});
assert.equal(snapshots.at(-1).status, 'running', 'approval wait ends on the real result');
assert.equal(snapshots.at(-1).entries.at(-1).output, '');
assert.equal(snapshots.at(-1).entries.at(-1).isError, true);
assert.equal(snapshots.at(-1).entries.at(-1).live, undefined);
send({type:'usage', usage:{promptTokens:10, completionTokens:4}, estimated:true});
send({type:'usage', usage:{promptTokens:7, completionTokens:3}});
collector.finish('done', 'Final report');
const trace = snapshots.at(-1);
assert.equal(trace.inputTokens, 7);
assert.equal(trace.outputTokens, 3);
assert.equal(trace.toolCalls, 1);
assert.equal(trace.entries[0].text, 'first second', 'cumulative thinking is not duplicated');
assert.equal(trace.entries[1].text, 'Checking the file', 'final text replaces streamed text');
assert.ok(trace.entries.every(entry => entry.endedAt));
assert.equal(trace.report, 'Final report');
assert.equal(readSubagentTrace({...trace, status:'waiting'}, true).status, 'interrupted');
assert.equal(readSubagentTrace({...trace, status:'done'}, true).status, 'done');
for (const malformed of [null, '', [], {taskId:'x'}, {...trace, status:'pretend'}, {...trace, entries:null}]) assert.equal(readSubagentTrace(malformed), undefined);
const huge = readSubagentTrace({...trace, prompt:'p'.repeat(100000), entries:Array.from({length:200}, (_, i) => ({id:String(i), kind:'tool', tool:'read_file', text:'a'.repeat(20000), output:'b'.repeat(20000), startedAt:-1}))});
assert.equal(huge.entries.length, TRACE_ENTRIES);
assert.equal(huge.entries.at(-1).id, '199');
assert.ok(huge.truncated);
assert.equal(huge.entries[0].startedAt, 0);
assert.ok(huge.prompt.length + huge.entries.reduce((n, e) => n + e.text.length + (e.output?.length ?? 0), 0) <= TRACE_CHARS);
assert.equal(trimDisplayEvent({type:'tool_call', id:'parent', tool:'task', args:{prompt:'x'}, subagent:huge}).subagent.entries.at(-1).id, '199');
assert.equal(readSubagentTrace({...trace, entries:[{...trace.entries[0],html:'<script>bad</script>'}]}).entries[0].html, undefined, 'stored HTML never bypasses host sanitization');
assert.equal(readSubagentTrace({...trace, apiKey:'secret', headers:{Authorization:'secret'}}).apiKey, undefined);
assert.equal(readSubagentTrace({...trace, apiKey:'secret', headers:{Authorization:'secret'}}).headers, undefined);
const groups = [[...Array.from({length:40},(_,i)=>({id:String(i),subagent:{...trace,prompt:'p'.repeat(8000),entries:[{id:'work',kind:'text',text:'s'.repeat(8000),startedAt:1}]}}))]];
const bounded = boundSubagentEvents(groups)[0];
assert.ok(bounded[0].subagent.truncated && bounded[0].subagent.entries.length === 0);
assert.equal(bounded.at(-1).subagent.entries.length, 1);
assert.equal(groups[0][0].subagent.entries.length, 1, 'aggregate trimming does not mutate model/display inputs');
const research = { version:1, provider:'parallel', outcome:'success', freshness:'unknown', sources:Array.from({length:20},(_,i)=>({id:String(i),url:`https://example.com/${i}`,title:'Documentation',excerpts:['x'.repeat(1200),'y'.repeat(1200)],retrievedAt:'now',route:'parallel'})), warnings:[] };
const entries = Array.from({length:120},(_,i)=>({id:String(i),kind:'tool',tool:'web_search',text:'{}',output:'sources',startedAt:1,research,structuredContent:{text:'s'.repeat(8000)}}));
const evidenceTrace = readSubagentTrace({...trace,entries});
const payloadSize = value => (value.prompt?.length ?? 0) + (value.description?.length ?? 0) + (value.model?.length ?? 0) + (value.effort?.length ?? 0) + (value.report?.length ?? 0) + (value.error?.length ?? 0) + value.entries.reduce((sum,e)=>sum+e.text.length+(e.tool?.length??0)+(e.output?.length??0)+(e.live?.length??0)+(e.research?JSON.stringify(e.research).length:0)+(e.structuredContent?JSON.stringify(e.structuredContent).length:0),0);
assert.ok(payloadSize(evidenceTrace) <= TRACE_CHARS);
assert.ok(evidenceTrace.truncated); assert.equal(evidenceTrace.entries.at(-1).research.sources.length,20);
assert.ok(evidenceTrace.entries.slice(0,-1).some(e=>!e.research || e.research.sources.length<20),'older source metadata is reclaimed');
assert.equal(entries[0].research.sources[0].excerpts[0].length,1200,'bounding never mutates input evidence');
const publications = [];
const evidenceCollector = new SubagentTraceCollector({...trace,entries:[],status:'running'},value=>publications.push(value));
for(let i=0;i<10;i++) {
 evidenceCollector.receive({type:'toolCall',id:String(i),tool:'web_search',args:{}});
 evidenceCollector.receive({type:'toolResult',id:String(i),tool:'web_search',output:'sources',research,structuredContent:{number:i}});
}
assert.ok(publications.every(value=>payloadSize(value)<=TRACE_CHARS),'every live publication obeys the aggregate budget');
const small = readSubagentTrace({...trace,entries:[{...entries[0],research:undefined,structuredContent:{number:1}}]});
assert.equal(small.entries[0].structuredContent.number,1);
const snapshotJson = JSON.stringify(publications.at(-1));
evidenceCollector.receive({type:'toolCall',id:'later',tool:'read_file',args:{}});
assert.equal(JSON.stringify(publications.at(-2)),snapshotJson,'metadata snapshots remain immutable');
collector.finish('cancelled');
assert.equal(snapshots.at(-1).status, 'cancelled');
console.log('subagent observation: immutable snapshots, real states, cumulative thinking, token accounting, bounded replay and display-only metadata passed');
