import { expect, test } from '@playwright/test';
import { installVscodeTheme } from './vscodeTheme';
import { openPageNavigation } from './navigation';
import { mkdir } from 'node:fs/promises';
for (const theme of ['dark','light'] as const) for (const locale of ['en','fa']) for (const width of [420,1440]) test(`interface sizing and complete hover surfaces (${theme}, ${locale}, ${width})`, async ({page}) => {
    await installVscodeTheme(page, theme);
    await page.setViewportSize({width,height:900});
    await page.addInitScript(() => { let state: unknown = {surfaceAppearance:{interfaceSize:18}}; const sent: unknown[]=[]; Object.assign(window,{sent,acquireVsCodeApi:()=>({getState:()=>state,setState:(v:unknown)=>state=v,postMessage:(m:unknown)=>sent.push(m)})}); });
    await page.goto('/');
    const post = async (message:object) => {await page.evaluate(m=>window.postMessage(m,'*'),message);};
    await post({type:'locale',locale}); await post({type:'showChat'});
    await mkdir('output/playwright/interface-size',{recursive:true});
    await page.screenshot({path:`output/playwright/interface-size/${theme}-${locale}-${width}-chat-18.png`,animations:'disabled'});
    await expect(page.locator('.composer-engine-picker .dropdown-trigger')).toHaveCSS('font-size','18px');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
    await page.locator('.composer-engine-picker .dropdown-trigger').click();
    await page.screenshot({path:`output/playwright/interface-size/${theme}-${locale}-${width}-engine-menu.png`,animations:'disabled'});
    await page.locator('.composer-engine-picker').getByRole('option').last().click();
    expect(await page.evaluate(()=> (window as unknown as {sent:object[]}).sent)).toContainEqual({type:'engineSelect',engine:'opencode'});
    if (!await page.locator('.workspace-sidebar').isVisible()) await page.locator('.toolbar > .sidebar-toggle').click();
    await post({type:'sessionList',currentId:'empty',items:[{id:'empty',title:'Empty conversation',workspace:'/project',updatedAt:Date.now()}]});
    await page.locator('.session-row').hover();
    await page.locator('.session-row-delete').click();
    const confirmation = page.locator('.session-row-confirm');
    const bounds = await confirmation.evaluate(el => {
        const sidebar = el.closest('.workspace-sidebar')!.getBoundingClientRect();
        return [...el.querySelectorAll('button')].every(button => {
            const rect = button.getBoundingClientRect();
            return rect.left >= sidebar.left && rect.right <= sidebar.right;
        });
    });
    expect(bounds).toBe(true);
    await page.screenshot({path:`output/playwright/interface-size/${theme}-${locale}-${width}-delete.png`,animations:'disabled'});
    await confirmation.locator('.session-danger').click();
    expect(await page.evaluate(()=> (window as unknown as {sent:object[]}).sent)).toContainEqual({type:'deleteSession',id:'empty'});
    await post({type:'openSettings'});
    const proxy=page.locator('.settings-configure-proxy');
    await proxy.scrollIntoViewIfNeeded();
    const gap=await proxy.evaluate(el=>{const a=el.getBoundingClientRect(),b=el.parentElement!.getBoundingClientRect();return b.width-a.width;});
    expect(gap).toBeLessThanOrEqual(2);
    await openPageNavigation(page);await page.locator('[data-section=appearance]').click();
    await expect(page.locator('#appearance-interface-size')).toHaveText('18 px');
    await page.screenshot({path:`output/playwright/interface-size/${theme}-${locale}-${width}-appearance-18.png`,animations:'disabled'});
    await page.locator('#appearance-interface-size').click();await page.getByRole('option',{name:'12 px',exact:true}).click();
    await expect(page.locator('#appearance-interface-size')).toHaveCSS('font-size','12px');
    await openPageNavigation(page);await expect(page.locator('.sidebar-item').first()).toHaveCSS('font-size','12px');
    await page.locator('[data-section=agents]').click();
    await post({type:'agentsState',profiles:[{name:'explore',description:'Inspect the project',source:'builtin',editable:false}]});
    const layout = await page.locator('.agents-page .inventory-split').boundingBox();
    const toolbar = await page.locator('.agents-page .inventory-toolbar').boundingBox();
    expect(Math.abs(layout!.x + layout!.width/2 - toolbar!.x - toolbar!.width/2)).toBeLessThan(2);
    await page.screenshot({path:`output/playwright/interface-size/${theme}-${locale}-${width}-agents.png`,animations:'disabled'});
    await openPageNavigation(page);
    await page.locator('[data-section=providers]').click();
    await page.locator('.cred-head .page-add').click();
    const search=page.locator('#cred-provider-input');await search.fill('https://custom.example/v1');
    await expect(page.locator('.connection-drawer input[placeholder="https://api.openai.com/v1"]')).toHaveValue('https://custom.example/v1');
    await mkdir('output/playwright/interface-size',{recursive:true});
    await page.screenshot({path:`output/playwright/interface-size/${theme}-${locale}-${width}-provider.png`,animations:'disabled'});
    await page.keyboard.press('Escape');
});
