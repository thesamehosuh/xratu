/**
 * Centralized UI strings. Xratu is Persian-first: `LOCALE` below defaults to
 * 'fa' deliberately (the audience is Iranian students, many of whom run
 * English-language VS Code installs - following navigator.language would
 * silently flip them to Persian… or worse). The Settings page exposes the
 * flip (setLocale); the host persists the choice across sessions.
 */

export type Locale = 'fa' | 'en';

// The host bakes the persisted choice into the webview HTML at resolve time
// (window.XRATU_LOCALE in _getHtmlForWebview) so the very first paint - and
// every subsequent render - uses the right language with no host round-trip.
// Falls back to 'fa' when the bootstrap is absent (Persian-first default).
declare global {
    interface Window {
        XRATU_LOCALE?: Locale;
    }
}

let LOCALE: Locale =
    typeof window !== 'undefined' && window.XRATU_LOCALE === 'en' ? 'en' : 'fa';

/**
 * Keep the document language in sync with the UI locale. Screen readers,
 * spellcheck and `:lang()` selectors read `<html lang>`, which ships as a
 * static default in index.html and must follow a runtime locale flip.
 */
function applyDocumentLang(locale: Locale): void {
    if (typeof document !== 'undefined') {
        document.documentElement.lang = locale;
    }
}

applyDocumentLang(LOCALE);

