type Dict = typeof fa;

let STRINGS: Dict = LOCALE === 'fa' ? fa : (en as Dict);

/** Flip the UI language (Settings page). Takes effect immediately for every
 *  subsequent t()/tf() call; callers re-render via their own state. */
export function setLocale(locale: Locale): void {
    LOCALE = locale;
    STRINGS = locale === 'fa' ? fa : (en as Dict);
    applyDocumentLang(locale);
}

export function getLocale(): Locale {
    return LOCALE;
}

export type StringKey = keyof Dict;

export function t(key: StringKey): string {
    return STRINGS[key] as unknown as string;
}

/** Like t() but tolerates unknown keys (host posts string keys over the
 *  wire) - an unrecognized key renders as-is instead of throwing. */
export function tOrRaw(key: string): string {
    return key in STRINGS ? (STRINGS as Record<string, string>)[key] : key;
}

/** Translate a key with `{name}` placeholder interpolation - banner
 *  messages composed host-side carry their parameters alongside the key.
 *  Single-pass substitution: sequential replace() would re-scan and expand
 *  `{placeholders}` appearing inside a param VALUE. */
export function tf(key: string, params?: Record<string, string>): string {
    const s = tOrRaw(key);
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, (match, name: string) =>
        Object.prototype.hasOwnProperty.call(params, name) ? params[name] : match
    );
}
